-- Crear tabla de tipos de reunión
CREATE TABLE MM_TIPO_MEET (
    ID_TIPO_MEET NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL,
    FECHA_CREACION DATE DEFAULT SYSDATE
