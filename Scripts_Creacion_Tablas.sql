-- Crear trigger para actualizar fecha de modificación
CREATE OR REPLACE TRIGGER TRG_MM_MEET_UPDATE
    BEFORE UPDATE ON MM_MEET
    FOR EACH ROW
BEGIN
    :NEW.FECHA_MODIFICACION := SYSDATE;
END;
/

-- Crear trigger para validar fechas
CREATE OR REPLACE TRIGGER TRG_MM_MEET_VALIDATE_DATES
    BEFORE INSERT OR UPDATE ON MM_MEET
    FOR EACH ROW
BEGIN
    -- Validar que la fecha de fin no sea anterior a la fecha de inicio
    IF :NEW.FECHA_FIN IS NOT NULL AND :NEW.FECHA_FIN < :NEW.FECHA_INICIO THEN
        RAISE_APPLICATION_ERROR(-20001, 'La fecha de fin no puede ser anterior a la fecha de inicio');
    END IF;
    
    -- Validar que la hora de fin no sea anterior a la hora de inicio
    IF :NEW.HORA_FIN IS NOT NULL AND :NEW.HORA_INICIO IS NOT NULL 
       AND :NEW.HORA_FIN <= :NEW.HORA_INICIO THEN
        RAISE_APPLICATION_ERROR(-20002, 'La hora de fin debe ser posterior a la hora de inicio');
    END IF;
END;
/

